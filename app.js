const dailyCards = document.getElementById("dailyCards");
let lang = localStorage.getItem("dkgl-lang") || "en";
let section = location.hash.replace("#","") || localStorage.getItem("dkgl-section") || "daily";
if(!T[lang]) lang="en";
if(!["daily","alliances","events","heroes","tips"].includes(section)) section="daily";

function renderDaily(){
  dailyCards.innerHTML = DAILY[lang].map(s => `
    <article class="routine theme-${s.color}">
      <div class="section-head">
        <span class="step">${s.n}</span>
        <div>
          <p class="mini">DAILY ROUTINE</p>
          <h2>${s.title}</h2>
        </div>
      </div>
      <p class="section-text">${s.text}</p>
      <div class="shots ${s.images.length===1 ? "one":""}">
        ${s.images.map(([f,label])=>`
          <figure>
            <div class="shot-label">${label}</div>
            <a href="assets/${f}" target="_blank" rel="noopener">
              <img src="assets/${f}" alt="${label}" loading="lazy">
            </a>
          </figure>
        `).join("")}
      </div>
    </article>
  `).join("");
}

function applyLang(){
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(T[lang][key]) el.textContent=T[lang][key];
  });
  document.querySelectorAll(".lang").forEach(b=>b.classList.toggle("active",b.dataset.lang===lang));
  renderDaily();
}

function showSection(name, updateHash=true){
  section=name;
  localStorage.setItem("dkgl-section",section);
  document.querySelectorAll(".page").forEach(p=>p.classList.toggle("active",p.dataset.page===section));
  document.querySelectorAll(".nav-btn").forEach(b=>b.classList.toggle("active",b.dataset.section===section));
  if(updateHash) history.replaceState(null,"","#"+section);
  document.getElementById("mainNav").classList.remove("open");
  document.getElementById("mobileMenu").setAttribute("aria-expanded","false");
  window.scrollTo({top:0,behavior:"smooth"});
}

document.querySelectorAll(".lang").forEach(b=>b.addEventListener("click",()=>{
  lang=b.dataset.lang;
  localStorage.setItem("dkgl-lang",lang);
  applyLang();
}));

document.querySelectorAll(".nav-btn").forEach(b=>b.addEventListener("click",()=>showSection(b.dataset.section)));

document.getElementById("mobileMenu").addEventListener("click",()=>{
  const nav=document.getElementById("mainNav");
  const open=nav.classList.toggle("open");
  document.getElementById("mobileMenu").setAttribute("aria-expanded",String(open));
});

window.addEventListener("hashchange",()=>{
  const h=location.hash.replace("#","");
  if(["daily","alliances","events","heroes","tips"].includes(h)) showSection(h,false);
});

applyLang();
showSection(section,false);
