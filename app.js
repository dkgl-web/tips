let lang = localStorage.getItem("dkgl-lang") || "en";
let route = location.hash.replace("#","") || "home";
const ROUTES=["home","daily","alliances","events","heroes","tips"];
if(!I18N[lang]) lang="en";
if(!ROUTES.includes(route)) route="home";

function renderDaily(){
 const target=document.getElementById("dailyGrid");
 target.innerHTML=DAILY[lang].map(item=>`
  <article class="guide-card">
    <div class="guide-head">
      <span class="guide-number">${item.n}</span>
      <div><h3>${item.title}</h3><p>${item.text}</p></div>
    </div>
    <div class="guide-images ${item.imgs.length===1?"one":item.imgs.length===2?"two":""}">
      ${item.imgs.map(([file,label])=>`
       <div class="guide-shot">
        <b>${label}</b>
        <a href="assets/${file}" target="_blank" rel="noopener"><img src="assets/${file}" alt="${label}" loading="lazy"></a>
       </div>`).join("")}
    </div>
    ${item.note?`<div class="guide-note">${item.note}</div>`:""}
  </article>`).join("");
}

function renderTips(){
 const labels=I18N[lang].tt;
 const files=["tt1.jpg","tt2.jpg","tt3.jpg","tt4.jpg"];
 const target=document.getElementById("teleportSteps");
 if(target){
   target.innerHTML=files.map((file,i)=>`
     <div class="step-card">
      <b>${labels[i]}</b>
      <a href="assets/${file}" target="_blank" rel="noopener"><img src="assets/${file}" alt="${labels[i]}" loading="lazy"></a>
     </div>`).join("");
 }

 let drone=document.getElementById("droneGuide");
 if(!drone){
   const tipsPage=document.querySelector('[data-page="tips"]');
   drone=document.createElement("article");
   drone.id="droneGuide";
   drone.className="feature-guide drone-guide";
   tipsPage.appendChild(drone);
 }
 drone.innerHTML=`
   <div class="feature-copy">
     <span class="feature-badge">${I18N[lang].droneBadge}</span>
     <h3>${I18N[lang].droneTitle}</h3>
     <p>${I18N[lang].droneText}</p>
   </div>
   <div class="drone-visual">
     <a href="assets/dron.webp" target="_blank" rel="noopener">
       <img src="assets/dron.webp" alt="${I18N[lang].droneTitle}" loading="lazy">
     </a>
   </div>`;
}

function applyLanguage(){
 document.documentElement.lang=lang;
 document.querySelectorAll("[data-i18n]").forEach(el=>{
   const k=el.dataset.i18n;
   if(I18N[lang][k]) el.textContent=I18N[lang][k];
 });
 document.querySelectorAll(".lang").forEach(b=>b.classList.toggle("active",b.dataset.lang===lang));
 renderDaily(); renderTips();
}

function showRoute(name, updateHash=true){
 route=name;
 document.querySelectorAll(".page").forEach(p=>p.classList.toggle("active",p.dataset.page===name));
 document.querySelectorAll(".nav-link").forEach(b=>b.classList.toggle("active",b.dataset.route===name));
 if(updateHash) history.replaceState(null,"","#"+name);
 document.getElementById("mainNav").classList.remove("open");
 document.getElementById("navToggle").setAttribute("aria-expanded","false");
 window.scrollTo({top:0,behavior:"smooth"});
}

document.querySelectorAll("[data-route]").forEach(el=>el.addEventListener("click",()=>showRoute(el.dataset.route)));
document.querySelectorAll(".lang").forEach(el=>el.addEventListener("click",()=>{
 lang=el.dataset.lang;localStorage.setItem("dkgl-lang",lang);applyLanguage();
}));
document.getElementById("navToggle").addEventListener("click",()=>{
 const nav=document.getElementById("mainNav"), open=nav.classList.toggle("open");
 document.getElementById("navToggle").setAttribute("aria-expanded",String(open));
});
window.addEventListener("hashchange",()=>{const h=location.hash.replace("#","");if(ROUTES.includes(h))showRoute(h,false)});

applyLanguage();
showRoute(route,false);
